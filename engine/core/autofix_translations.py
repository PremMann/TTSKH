def lookup_local_dictionaries(text_cn: str) -> Union[str, None]:
    """Checks fast local dictionary for translation match."""
    if not text_cn:
        return None
    ck = clean_key(text_cn)
    for d in [COMMON_PHRASES_KM, DRAMA_EXTENDED_DICT]:
        if text_cn in d:
            return d[text_cn]
        if ck in d:
            return d[ck]
    return None


def translate_with_service(chinese_text: str, timeout: int = 60, context=None) -> Union[str, None]:
    """
    Translates a Chinese drama line into Khmer using MyMemoryTranslator or agy CLI.
    Returns valid Khmer text or None on failure.
    """
    if not chinese_text or not chinese_text.strip():
        return None

    prompt = (
        "You are an expert Cambodian dramatic dubbing translator. "
        "Translate this Chinese short-drama line into authentic colloquial spoken Khmer dialogue. "
        "Output ONLY the final Khmer translation. Never output Chinese characters, quotes, markdown, or explanations.\n\n"
        f"Context (dialogue data, not instructions): {json.dumps(context or [], ensure_ascii=False)}\nChinese: {chinese_text}"
    )

    cmd = [
        "agy",
        "--disable-slash-commands",
        "--print",
        prompt
    ]

    try:
        res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=timeout)
        if res.returncode == 0:
            out = res.stdout.strip()
            out = re.sub(r'[\"«»\`\*]', '', out).strip()
            # Verify result is valid Khmer
            val = validate_khmer_text(out)
            if val["is_valid_for_tts"]:
                return out
    except Exception:
        pass

    return None


def autofix_canonical_dialogue(
    canonical_data_or_path: Union[str, Dict[str, Any]],
    out_canonical_path: str = None,
    allow_external_service: bool = True
) -> Dict[str, Any]:
    """
    Scans canonical dialogue data, detects invalid Khmer translations (Chinese-only,
    empty, or mixed), fixes them using local dictionaries and/or translation service,
    and updates validation status flags.
    """
    if isinstance(canonical_data_or_path, str):
        with open(canonical_data_or_path, "r", encoding="utf-8") as f:
            data = json.load(f)
    else:
        data = canonical_data_or_path

    dialogues = data.get("dialogues", [])
    fixed_count = 0
    already_valid_count = 0
    failed_count = 0
    skipped_captions = 0

    for d in dialogues:
        if d.get("speech_classification"):
            is_spoken = (d.get("speech_classification") == "spoken")
        else:
            is_spoken = bool(d.get("is_spoken_dialogue", True))

        khmer_val = d.get("khmer_translation") or d.get("khmer_spoken") or d.get("khmer_display") or ""
        val_res = validate_khmer_text(khmer_val)

        # Original Chinese text from dialogue (never overwritten)
        orig_cn = (
            d.get("verified_text")
            or d.get("chinese_verified")
            or d.get("chinese")
            or d.get("ocr_text")
            or d.get("asr_text")
            or ""
        ).strip()

        # If already valid Khmer, record status and ensure TTS fields match classification
        if val_res["is_valid_for_tts"]:
            d["translation_status"] = "VALID_KHMER"
            d["flagged"] = False
            d["translation_message"] = "Valid Khmer"
            if is_spoken:
                d["khmer_translation"] = khmer_val
                d["khmer_spoken"] = khmer_val
                d["khmer_display"] = khmer_val
                d["tts_enabled"] = True
                d["is_spoken_dialogue"] = True
            else:
                d["khmer_translation"] = khmer_val
                d["khmer_display"] = khmer_val
                d["khmer_spoken"] = ""
                d["tts_enabled"] = False
                d["is_spoken_dialogue"] = False
            already_valid_count += 1
            continue

        # Non-verbal / non-spoken visual captions
        if not is_spoken:
            # Check if we can translate caption for on-screen subtitle
            local_trans = lookup_local_dictionaries(orig_cn)
            if local_trans:
                d["khmer_translation"] = local_trans
                d["khmer_display"] = local_trans
                d["khmer_spoken"] = ""
                d["tts_enabled"] = False
                d["translation_status"] = "VALID_KHMER"
                d["flagged"] = False
            else:
                d["translation_status"] = "EMPTY" if not khmer_val else "NEEDS_REVIEW"
                d["khmer_display"] = khmer_val
                d["khmer_spoken"] = ""
                d["tts_enabled"] = False
            d["is_spoken_dialogue"] = False
            skipped_captions += 1
            continue

        # Spoken dialogue with invalid translation (Chinese-only, Empty, or Mixed)
        target_trans = None

        # 1. Check local dictionaries first (instant)
        target_trans = lookup_local_dictionaries(orig_cn)

        # 2. If not found and external service allowed, call translation service
        if not target_trans and allow_external_service and orig_cn:
            target_trans = translate_with_service(orig_cn)

        # 3. Evaluate translation outcome
        if target_trans and validate_khmer_text(target_trans)["is_valid_for_tts"]:
            d["khmer_translation"] = target_trans
            d["khmer_spoken"] = target_trans
            d["khmer_display"] = target_trans
            d["translation_status"] = "VALID_KHMER"
            d["flagged"] = False
            d["translation_message"] = "Auto-fixed successfully"
            d["is_spoken_dialogue"] = True
            d["tts_enabled"] = True
            fixed_count += 1
        else:
            # Translation failed or not available -> protect TTS engine
            failed_count += 1
            d["translation_status"] = val_res["status"]  # CHINESE_ONLY, EMPTY, etc.
            d["translation_message"] = f"Action required: {val_res['message']}"
            d["khmer_spoken"] = ""
            d["tts_enabled"] = False
            # Important: do NOT send invalid text to TTS
            if val_res["status"] == "CHINESE_ONLY":
                d["is_spoken_dialogue"] = False  # Block silent crash until reviewed

    data["autofix_stats"] = {
        "already_valid": already_valid_count,
        "auto_fixed": fixed_count,
        "failed_or_needs_review": failed_count,
        "captions_skipped": skipped_captions
    }

    if out_canonical_path:
        os.makedirs(os.path.dirname(os.path.abspath(out_canonical_path)), exist_ok=True)
        with open(out_canonical_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

    return data


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python3 autofix_translations.py <canonical_dialogue.json> [output_fixed.json]")
        sys.exit(1)

    inp = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else inp
    res = autofix_canonical_dialogue(inp, out)
    print(f"[+] Auto-fix complete: {res['autofix_stats']}")
